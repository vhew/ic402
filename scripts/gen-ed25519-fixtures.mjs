#!/usr/bin/env node
// Generates test/fixtures/ed25519/Vectors.mo from the vendored JSON beside it.
//
// The JSON files are the source of truth (provenance and licences in the README in
// that directory); Vectors.mo is derived so Motoko can consume them. Deterministic — CI
// regenerates it and fails on a diff, so the two can never drift.
//
//   node scripts/gen-ed25519-fixtures.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'test', 'fixtures', 'ed25519');
const read = (f) => JSON.parse(readFileSync(join(dir, f), 'utf8'));

// A Motoko Blob literal: every byte as a \xx escape.
const blob = (hex) => {
  if (hex.length % 2 !== 0 || !/^[0-9a-fA-F]*$/.test(hex)) throw new Error(`bad hex: ${hex}`);
  return '"' + hex.toLowerCase().replace(/(..)/g, '\\$1') + '"';
};
const text = (s) => JSON.stringify(s); // JSON string escaping is valid Motoko text escaping here
const bool = (v) => {
  if (typeof v !== 'boolean') throw new Error(`expected a boolean, got ${v}`);
  return String(v);
};

const lines = [];
const out = (s) => lines.push(s);

out(
  '// GENERATED by scripts/gen-ed25519-fixtures.mjs from the JSON in this directory — do not edit.',
);
out('// CI regenerates this file and fails on any diff. Provenance and licences: README.md here.');
out('module {');
out(
  '  public type Wycheproof = { tcId : Nat; flag : Text; valid : Bool; pub : Blob; msg : Blob; sig : Blob };',
);
out('  public type Rfc8032 = { name : Text; seed : Blob; pub : Blob; msg : Blob; sig : Blob };');
out('  public type Speccheck = { index : Nat; pub : Blob; msg : Blob; sig : Blob };');
out(
  '  public type Regression = { name : Text; valid : Bool; pub : Blob; msg : Blob; sig : Blob };',
);
out('');

// ── Wycheproof ──
const wp = read('wycheproof_ed25519.json');
let wpCount = 0;
out('  /// C2SP/wycheproof testvectors_v1/ed25519_test.json — every test, in file order.');
out('  public let wycheproof : [Wycheproof] = [');
for (const g of wp.testGroups) {
  for (const t of g.tests) {
    if (t.flags.length !== 1) throw new Error(`tcId ${t.tcId}: expected exactly one flag`);
    if (t.result !== 'valid' && t.result !== 'invalid')
      throw new Error(`tcId ${t.tcId}: result ${t.result}`);
    out(
      `    { tcId = ${t.tcId}; flag = ${text(t.flags[0])}; valid = ${t.result === 'valid'}; pub = ${blob(g.publicKey.pk)}; msg = ${blob(t.msg)}; sig = ${blob(t.sig)} },`,
    );
    wpCount++;
  }
}
out('  ];');
if (wpCount !== wp.numberOfTests) throw new Error(`wycheproof: ${wpCount} != ${wp.numberOfTests}`);
out('');

// ── RFC 8032 §7.1 ──
out('  /// RFC 8032 section 7.1 — the five Ed25519 test vectors.');
out('  public let rfc8032 : [Rfc8032] = [');
for (const v of read('rfc8032.json')) {
  out(
    `    { name = ${text(v.name)}; seed = ${blob(v.secretKey)}; pub = ${blob(v.publicKey)}; msg = ${blob(v.message)}; sig = ${blob(v.signature)} },`,
  );
}
out('  ];');
out('');

// ── ed25519-speccheck ──
out('  /// novifinancial/ed25519-speccheck cases.json — the 12 policy-edge cases, by index.');
out('  public let speccheck : [Speccheck] = [');
read('speccheck_cases.json').forEach((c, i) => {
  out(
    `    { index = ${i}; pub = ${blob(c.pub_key)}; msg = ${blob(c.message)}; sig = ${blob(c.signature)} },`,
  );
});
out('  ];');
out('');

// ── Regressions ──
const r = read('regressions.json');
out('  /// Vectors that pinned the mo:ed25519 0.1.0 defects (see regressions.json for notes).');
out('  public let regressions : [Regression] = [');
out(
  `    { name = "pinned (EngramX report)"; valid = ${bool(r.pinned.valid)}; pub = ${blob(r.pinned.pub)}; msg = ${blob(r.pinned.msg)}; sig = ${blob(r.pinned.sig)} },`,
);
r.band.forEach((b, i) => {
  out(
    `    { name = "band ${i} (0.1.0 ${b.mo_ed25519_0_1_0})"; valid = ${bool(b.valid)}; pub = ${blob(b.pub)}; msg = ${blob(b.msg)}; sig = ${blob(b.sig)} },`,
  );
});
r.malleated.forEach((m, i) => {
  out(
    `    { name = "malleated ${i}: original"; valid = true; pub = ${blob(m.pub)}; msg = ${blob(m.msg)}; sig = ${blob(m.sig)} },`,
  );
  out(
    `    { name = "malleated ${i}: S + 2^256 mod L"; valid = false; pub = ${blob(m.pub)}; msg = ${blob(m.msg)}; sig = ${blob(m.malleated)} },`,
  );
});
out('  ];');
out('');

// ── Policy vectors ──
const pol = read('policy.json').vectors;
out('  /// Vectors that each pin ONE check of the policy (see policy.json for how each is built).');
out('  public let policy : [Regression] = [');
for (const v of pol) {
  out(
    `    { name = ${text(v.name)}; valid = ${bool(v.valid)}; pub = ${blob(v.pub)}; msg = ${blob(v.msg)}; sig = ${blob(v.sig)} },`,
  );
}
out('  ];');
out('}');

writeFileSync(join(dir, 'Vectors.mo'), lines.join('\n') + '\n');
console.log(
  `Vectors.mo: ${wpCount} wycheproof, ${read('rfc8032.json').length} rfc8032, ${read('speccheck_cases.json').length} speccheck, ${1 + r.band.length + 2 * r.malleated.length} regressions, ${pol.length} policy`,
);
