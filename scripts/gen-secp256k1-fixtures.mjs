#!/usr/bin/env node
// Generates test/fixtures/secp256k1/Vectors.mo from the vendored JSON beside it.
//
// The JSON files are the source of truth (provenance and licences in the README in
// that directory); Vectors.mo is derived so Motoko can consume them. Deterministic — CI
// regenerates it and fails on a diff, so the two can never drift.
//
// ic402's ecRecover takes a 32-byte digest, so each Wycheproof message is hashed here with
// SHA-256 (the file's hash), and each public key is emitted in the compressed SEC1 form
// ecRecover returns.
//
//   node scripts/gen-secp256k1-fixtures.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'test', 'fixtures', 'secp256k1');
const read = (f) => JSON.parse(readFileSync(join(dir, f), 'utf8'));

const isHex = (hex) => hex.length % 2 === 0 && /^[0-9a-fA-F]*$/.test(hex);
// A Motoko Blob literal: every byte as a \xx escape.
const blob = (hex) => {
  if (!isHex(hex)) throw new Error(`bad hex: ${hex}`);
  return '"' + hex.toLowerCase().replace(/(..)/g, '\\$1') + '"';
};
const text = (s) => JSON.stringify(s); // JSON string escaping is valid Motoko text escaping here
const sha256 = (hex) => createHash('sha256').update(Buffer.from(hex, 'hex')).digest('hex');
// 04 || x || y  →  02/03 || x
const compress = (uncompressed) => {
  if (!isHex(uncompressed) || uncompressed.length !== 130 || !uncompressed.startsWith('04'))
    throw new Error(`bad uncompressed key: ${uncompressed}`);
  const x = uncompressed.slice(2, 66);
  const yOdd = BigInt('0x' + uncompressed.slice(66)) % 2n === 1n;
  return (yOdd ? '03' : '02') + x;
};

const lines = [];
const out = (s) => lines.push(s);

out(
  '// GENERATED by scripts/gen-secp256k1-fixtures.mjs from the JSON in this directory — do not edit.',
);
out('// CI regenerates this file and fails on any diff. Provenance and licences: README.md here.');
out('module {');
out(
  '  public type Wycheproof = { tcId : Nat; flags : [Text]; valid : Bool; pub : Blob; hash : Blob; sig : Blob };',
);
out(
  '  public type Policy = { name : Text; pub : Blob; hash : Blob; r : Blob; s : Blob; v : Nat8 };',
);
out('');

// ── Wycheproof ──
const wpFile = 'ecdsa_secp256k1_sha256_p1363_test.json';
const wp = read(wpFile);
let wpCount = 0;
out(`  /// C2SP/wycheproof testvectors_v1/${wpFile} — every test, in file order.`);
out('  /// `hash` is SHA-256(msg); `pub` is the group key, compressed; `sig` is r || s as given.');
out('  public let wycheproof : [Wycheproof] = [');
for (const g of wp.testGroups) {
  if (g.type !== 'EcdsaP1363Verify' || g.sha !== 'SHA-256' || g.publicKey.curve !== 'secp256k1')
    throw new Error(`unexpected group: ${g.type} ${g.sha} ${g.publicKey.curve}`);
  const pub = compress(g.publicKey.uncompressed);
  for (const t of g.tests) {
    if (t.result !== 'valid' && t.result !== 'invalid')
      throw new Error(`tcId ${t.tcId}: result ${t.result}`);
    if (t.flags.length === 0) throw new Error(`tcId ${t.tcId}: no flags`);
    const flags = '[' + t.flags.map(text).join(', ') + ']';
    out(
      `    { tcId = ${t.tcId}; flags = ${flags}; valid = ${t.result === 'valid'}; pub = ${blob(pub)}; hash = ${blob(sha256(t.msg))}; sig = ${blob(t.sig)} },`,
    );
    wpCount++;
  }
}
out('  ];');
if (wpCount !== wp.numberOfTests) throw new Error(`wycheproof: ${wpCount} != ${wp.numberOfTests}`);
out('');

// ── Policy vectors ──
const pol = read('policy.json').vectors;
out('  /// Vectors for behaviour Wycheproof does not pin (see policy.json for how each is built).');
out('  public let policy : [Policy] = [');
for (const v of pol) {
  if (!Number.isInteger(v.v) || v.v < 0 || v.v > 1) throw new Error(`${v.name}: v ${v.v}`);
  for (const k of ['hash', 'r', 's'])
    if (v[k].length !== 64) throw new Error(`${v.name}: ${k} is not 32 bytes`);
  if (v.pub.length !== 66) throw new Error(`${v.name}: pub is not 33 bytes`);
  out(
    `    { name = ${text(v.name)}; pub = ${blob(v.pub)}; hash = ${blob(v.hash)}; r = ${blob(v.r)}; s = ${blob(v.s)}; v = ${v.v} },`,
  );
}
out('  ];');
out('}');

writeFileSync(join(dir, 'Vectors.mo'), lines.join('\n') + '\n');
console.log(`Vectors.mo: ${wpCount} wycheproof, ${pol.length} policy`);
